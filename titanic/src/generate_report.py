"""
Titanic Survival — Data Quality, Drift & Model Performance Monitoring

Generates three HTML reports in the reports/ directory:
  1. quality_report.html      — dataset overview and column statistics
  2. monitoring_report.html   — feature drift analysis (reference vs. current)
  3. performance_report.html  — model performance metrics on current data

Usage:
  python generate_report.py            # generate all reports and open in browser
  python generate_report.py --check    # headless mode: print alerts, exit non-zero if issues found
"""

import argparse
import sys
import webbrowser
from datetime import datetime
from pathlib import Path

import mlflow
import mlflow.sklearn
import numpy as np
import pandas as pd
from evidently import Report
from evidently.presets import DataDriftPreset
from sklearn.metrics import accuracy_score, precision_score, recall_score, f1_score, roc_auc_score
from sklearn.model_selection import train_test_split

# ── Paths & Config ──────────────────────────────────────────────────────────
PROJECT_DIR = Path(__file__).resolve().parent.parent
DATA_DIR = PROJECT_DIR / 'data'
REPORTS_DIR = PROJECT_DIR / 'reports'
PROCESSED_FILE = DATA_DIR / 'processed_titanic.csv'

DRIFT_THRESHOLD = 0.3
PERFORMANCE_THRESHOLDS = {
    "accuracy": 0.75,
    "precision": 0.70,
    "recall": 0.65,
    "f1_score": 0.70,
    "roc_auc": 0.75,
}

CSS = """
body { font-family: system-ui, sans-serif; max-width: 800px; margin: 2rem auto; padding: 0 1rem; color: #333; }
h1 { font-size: 1.4rem; }
h2 { font-size: 1.1rem; margin-top: 1.5rem; }
p { margin: 0.5rem 0; }
table { border-collapse: collapse; width: 100%; margin: 0.5rem 0; font-size: 0.9rem; }
th, td { border: 1px solid #ccc; padding: 6px 10px; text-align: left; }
th { background: #f5f5f5; }
td.num { text-align: right; }
.ok { color: green; }
.warn { color: #c60; }
.bad { color: red; }
footer { margin-top: 2rem; font-size: 0.8rem; color: #999; }
"""


# ── Data Loading ────────────────────────────────────────────────────────────

def load_data(path=PROCESSED_FILE):
    df = pd.read_csv(path)
    reference, current = train_test_split(
        df, test_size=0.2, random_state=42, stratify=df['Survived']
    )
    return df, reference, current


# ── Quality Report ──────────────────────────────────────────────────────────

def build_quality_report(dataframe, timestamp):
    rows, cols = dataframe.shape
    survival_rate = dataframe['Survived'].mean() * 100

    col_rows = ""
    for col in dataframe.columns:
        dtype = str(dataframe[col].dtype)
        missing = int(dataframe[col].isnull().sum())
        unique = int(dataframe[col].nunique())
        if dataframe[col].dtype in ('float64', 'int64'):
            col_rows += (
                f"<tr><td>{col}</td><td>{dtype}</td><td class='num'>{unique}</td>"
                f"<td class='num'>{missing}</td><td class='num'>{dataframe[col].mean():.2f}</td>"
                f"<td class='num'>{dataframe[col].std():.2f}</td><td class='num'>{dataframe[col].min():.2f}</td>"
                f"<td class='num'>{dataframe[col].max():.2f}</td></tr>\n"
            )
        else:
            col_rows += (
                f"<tr><td>{col}</td><td>{dtype}</td><td class='num'>{unique}</td>"
                f"<td class='num'>{missing}</td><td class='num'>—</td><td class='num'>—</td>"
                f"<td class='num'>—</td><td class='num'>—</td></tr>\n"
            )

    return f"""<!DOCTYPE html>
<html><head><meta charset="UTF-8"><title>Data Quality Report</title><style>{CSS}</style></head>
<body>
<h1>Data Quality Report</h1>
<p>Generated {timestamp} &mdash; {rows:,} rows, {cols} columns, {int(dataframe.isnull().sum().sum())} missing values, survival rate {survival_rate:.1f}%</p>

<h2>Column Statistics</h2>
<table>
<tr><th>Column</th><th>Type</th><th>Unique</th><th>Missing</th><th>Mean</th><th>Std</th><th>Min</th><th>Max</th></tr>
{col_rows}</table>

<footer>Generated by generate_report.py</footer>
</body></html>"""


# ── Drift Report ────────────────────────────────────────────────────────────

def compute_drift(ref_data, cur_data):
    drift_report = Report(metrics=[DataDriftPreset()])
    snapshot = drift_report.run(reference_data=ref_data, current_data=cur_data)
    metrics = snapshot.dict()["metrics"]

    features = []
    for m in metrics:
        config = m.get("config", {})
        if "ValueDrift" not in config.get("type", ""):
            continue
        col = config.get("column", "")
        method = config.get("method", "")
        threshold = config.get("threshold", 0.1)
        score = float(m.get("value", 0))
        is_pvalue = "p_value" in method
        drifted = score < threshold if is_pvalue else score > threshold
        features.append({"column": col, "method": method, "score": score,
                         "threshold": threshold, "drifted": drifted})
    return features


def build_drift_report(ref_data, cur_data, drift_results, timestamp):
    drifted_count = sum(1 for f in drift_results if f["drifted"])
    total = len(drift_results)

    feature_rows = ""
    for f in drift_results:
        status = '<span class="bad">Drift</span>' if f["drifted"] else '<span class="ok">Stable</span>'
        feature_rows += (
            f"<tr><td>{f['column']}</td><td>{f['method']}</td>"
            f"<td class='num'>{f['score']:.4f}</td><td class='num'>{f['threshold']}</td>"
            f"<td>{status}</td></tr>\n"
        )

    if drifted_count == 0:
        summary = "No drift detected. The production data matches the training baseline."
    else:
        summary = f"{drifted_count} of {total} features drifted. Consider retraining."

    return f"""<!DOCTYPE html>
<html><head><meta charset="UTF-8"><title>Drift Monitoring Report</title><style>{CSS}</style></head>
<body>
<h1>Drift Monitoring Report</h1>
<p>Generated {timestamp} &mdash; Reference: {ref_data.shape[0]:,} rows, Current: {cur_data.shape[0]:,} rows</p>
<p><strong>{summary}</strong></p>

<h2>Feature Drift Details</h2>
<table>
<tr><th>Feature</th><th>Test Method</th><th>Score</th><th>Threshold</th><th>Status</th></tr>
{feature_rows}</table>

<p>Numerical features use Wasserstein distance; categorical features use Jensen&ndash;Shannon distance.
A feature is flagged when its score exceeds the threshold.</p>

<footer>Generated by generate_report.py using Evidently AI</footer>
</body></html>"""


# ── Model Performance Report ────────────────────────────────────────────────

def load_all_models():
    mlflow_db = Path(__file__).resolve().parent.parent / "mlflow.db"
    mlflow.set_tracking_uri(f"sqlite:///{mlflow_db}")
    client = mlflow.tracking.MlflowClient()

    registered_run_id = None
    registered_label = None
    model_name = "titanic_survival_model"
    versions = client.search_model_versions(f"name='{model_name}'")
    if versions:
        latest = max(versions, key=lambda v: int(v.version))
        registered_run_id = latest.run_id
        registered_label = f"{model_name} v{latest.version}"

    experiment = client.get_experiment_by_name("titanic_experiment")
    if experiment is None:
        return [], registered_label

    runs = client.search_runs(
        experiment_ids=[experiment.experiment_id],
        order_by=["metrics.f1_score DESC"],
    )

    models = []
    for run in runs:
        model_type = run.data.params.get("model_type", "Unknown")
        artifact_name = f"{model_type}_classifier"
        model_uri = f"runs:/{run.info.run_id}/{artifact_name}"
        try:
            loaded = mlflow.sklearn.load_model(model_uri)
        except Exception:
            continue
        is_registered = run.info.run_id == registered_run_id
        models.append({
            "name": model_type,
            "model": loaded,
            "run_id": run.info.run_id,
            "is_registered": is_registered,
            "label": f"{model_type} ({registered_label})" if is_registered else model_type,
        })

    models.sort(key=lambda m: (not m["is_registered"], m["name"]))
    return models, registered_label


def compute_performance(model, current_data):
    X = current_data.drop(columns=['Survived'])
    y = current_data['Survived']
    y_pred = model.predict(X)
    y_proba = model.predict_proba(X)[:, 1]
    return {
        "accuracy": accuracy_score(y, y_pred),
        "precision": precision_score(y, y_pred),
        "recall": recall_score(y, y_pred),
        "f1_score": f1_score(y, y_pred),
        "roc_auc": roc_auc_score(y, y_proba),
    }


def build_performance_report(all_model_results, registered_label, timestamp, n_samples):
    registered_metrics = {}

    model_sections = ""
    for entry in all_model_results:
        name = entry["label"]
        metrics = entry["metrics"]
        is_reg = entry["is_registered"]

        if is_reg:
            registered_metrics = metrics
            badge = ' <span style="background:#2563eb;color:#fff;padding:2px 8px;border-radius:4px;font-size:0.8rem;">Deployed</span>'
        else:
            badge = ""

        metric_rows = ""
        for mname, value in metrics.items():
            threshold = PERFORMANCE_THRESHOLDS.get(mname, 0)
            if value >= threshold:
                status = f'<span class="ok">OK (>= {threshold})</span>'
            else:
                status = f'<span class="bad">BELOW threshold ({threshold})</span>'
            metric_rows += (
                f"<tr><td>{mname}</td><td class='num'>{value:.4f}</td>"
                f"<td class='num'>{threshold:.2f}</td><td>{status}</td></tr>\n"
            )

        model_sections += f"""
<h2>{name}{badge}</h2>
<table>
<tr><th>Metric</th><th>Value</th><th>Threshold</th><th>Status</th></tr>
{metric_rows}</table>
"""

    degraded = [n for n, v in registered_metrics.items()
                if v < PERFORMANCE_THRESHOLDS.get(n, 0)]
    if not registered_metrics:
        summary = "No registered model found."
    elif not degraded:
        summary = "All metrics for the deployed model are within acceptable thresholds."
    else:
        summary = f"ALERT: {', '.join(degraded)} below threshold on deployed model. Consider retraining."

    return f"""<!DOCTYPE html>
<html><head><meta charset="UTF-8"><title>Model Performance Report</title><style>{CSS}</style></head>
<body>
<h1>Model Performance Report</h1>
<p>Generated {timestamp} &mdash; Deployed: {registered_label or 'N/A'} &mdash; Evaluated on {n_samples} samples (current data split)</p>
<p><strong>{summary}</strong></p>
{model_sections}
<footer>Generated by generate_report.py</footer>
</body></html>"""


# ── Alerting ────────────────────────────────────────────────────────────────

def check_alerts(drift_results, perf_metrics):
    """Print alerts to console and return True if any issues found."""
    alerts = []

    high_drift = [f for f in drift_results if f["drifted"]]
    if high_drift:
        cols = ", ".join(f["column"] for f in high_drift)
        alerts.append(f"DRIFT ALERT: {len(high_drift)} feature(s) drifted: {cols}")

    for name, value in perf_metrics.items():
        threshold = PERFORMANCE_THRESHOLDS.get(name, 0)
        if value < threshold:
            alerts.append(f"PERFORMANCE ALERT: {name} = {value:.4f} is below threshold {threshold}")

    if alerts:
        print("\n" + "=" * 60)
        print("MONITORING ALERTS")
        print("=" * 60)
        for alert in alerts:
            print(f"  !! {alert}")
        print("=" * 60)
    else:
        print("\nAll monitoring checks passed. No alerts.")

    return len(alerts) > 0


# ── Main ────────────────────────────────────────────────────────────────────

def generate_reports(check_only=False):
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M")

    print(f"Reading processed data from: {PROCESSED_FILE}...")
    df, reference, current = load_data()
    print(f"Loaded dataset: {df.shape[0]} rows, {df.shape[1]} columns")
    print(f"Reference (training baseline): {reference.shape[0]} rows")
    print(f"Current  (production simulation): {current.shape[0]} rows\n")

    # Drift analysis
    print("Running drift analysis...")
    drift_results = compute_drift(reference, current)
    drifted = sum(1 for f in drift_results if f["drifted"])
    print(f"Drift: {drifted} of {len(drift_results)} features drifted")

    # Model performance
    print("\nLoading all models for performance evaluation...")
    all_models, registered_label = load_all_models()
    all_model_results = []
    registered_metrics = {}
    if all_models:
        for entry in all_models:
            print(f"Evaluating {entry['label']} on current data...")
            metrics = compute_performance(entry["model"], current)
            for mname, value in metrics.items():
                print(f"  {mname}: {value:.4f}")
            entry["metrics"] = metrics
            all_model_results.append(entry)
            if entry["is_registered"]:
                registered_metrics = metrics
            print()
    else:
        print("No models found — skipping performance evaluation.")

    # Alerts (based on deployed model only)
    has_alerts = check_alerts(drift_results, registered_metrics)

    if check_only:
        return has_alerts

    # Generate HTML reports
    REPORTS_DIR.mkdir(exist_ok=True)

    quality_path = REPORTS_DIR / "quality_report.html"
    quality_path.write_text(build_quality_report(df, timestamp), encoding="utf-8")
    print(f"\nData quality report saved to {quality_path.resolve()}")

    monitoring_path = REPORTS_DIR / "monitoring_report.html"
    monitoring_path.write_text(
        build_drift_report(reference, current, drift_results, timestamp),
        encoding="utf-8",
    )
    print(f"Drift monitoring report saved to {monitoring_path.resolve()}")

    if all_model_results:
        perf_path = REPORTS_DIR / "performance_report.html"
        perf_path.write_text(
            build_performance_report(all_model_results, registered_label, timestamp, len(current)),
            encoding="utf-8",
        )
        print(f"Performance report saved to {perf_path.resolve()}")

    webbrowser.open(monitoring_path.resolve().as_uri())
    return has_alerts


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Generate monitoring reports")
    parser.add_argument(
        "--check", action="store_true",
        help="Headless mode: print alerts and exit non-zero if issues found (no HTML generated)",
    )
    args = parser.parse_args()

    has_issues = generate_reports(check_only=args.check)
    if args.check and has_issues:
        sys.exit(1)
